static inline void SRCDB_initGlobalVariables(void) {
  DCL_resetDF13(&SRCDB_gi);
  SRCDB_gi.a1 = SRCDB_GI1_2P2Z_A1;
  SRCDB_gi.a2 = SRCDB_GI1_2P2Z_A2;
  SRCDB_gi.a3 = SRCDB_GI1_2P2Z_A3;
  SRCDB_gi.b0 = SRCDB_GI1_2P2Z_B0;
  SRCDB_gi.b1 = SRCDB_GI1_2P2Z_B1;
  SRCDB_gi.b2 = SRCDB_GI1_2P2Z_B2;
  SRCDB_gi.b3 = SRCDB_GI1_2P2Z_B3;

  SRCDB_closeGiLoop = 0.0f;

  DCL_resetDF13(&SRCDB_gv);
  SRCDB_gv.a1 = SRCDB_GV1_2P2Z_A1;
  SRCDB_gv.a2 = SRCDB_GV1_2P2Z_A2;
  SRCDB_gv.a3 = SRCDB_GV1_2P2Z_A3;
  SRCDB_gv.b0 = SRCDB_GV1_2P2Z_B0;
  SRCDB_gv.b1 = SRCDB_GV1_2P2Z_B1;
  SRCDB_gv.b2 = SRCDB_GV1_2P2Z_B2;
  SRCDB_gv.b3 = SRCDB_GV1_2P2Z_B3;

  SRCDB_closeGvLoop = 0.0f;
}

#pragma FUNC_ALWAYS_INLINE(PACK_readSensedSignals)
static inline void PACK_readSensedSignals(void) {
  PACK_iPrimSensed_pu =
      ((float32_t)Pack_IPRIM_ADCREAD * Pack_ADC_PU_SCALE_FACTOR -
       Pack_IPRIMSensedOffset_pu) *
      1.0f;

  PACK_iREFPrimSensed_pu =
      ((float32_t)Pack_IREF_ADCREAD * Pack_ADC_PU_SCALE_FACTOR -
       Pack_iREFPRIMSensedOffset_pu) *
      1.0f;

  PACK_VPrimSensed_pu =
      ((float32_t)Pack_VPRIM_ADCREAD * Pack_ADC_PU_SCALE_FACTOR -
       Pack_VPRIMSensedOffset_pu) *
      1.0f;
  PACK_VSecSensed_pu =
      ((float32_t)Pack_VSEC_ADCREAD * Pack_ADC_PU_SCALE_FACTOR -
       Pack_VSECSensedOffset_pu) *
      1.0f;
}

