void EPWM_setPhaseShiftandTBPRD(uint32_t base1, uint32_t base2,
                                float32_t phaseshift, uint16_t period)//realize phase shift based on comparator
{
  EALLOW;

  PWM_PRD = EPWM_getTimeBasePeriod(base1);
  phaseshift = (phaseshift / 1.0f) * PWM_PRD;

  if (PACKBALANCE_POWER_FLOW == PACKBALANCE_POWER_FLOW_PRIM_SEC)
  {
    PWM_phaseshift = phaseshift;
    PACK_Sec_PWM_CMPA = PWM_phaseshift;
    PACK_Sec_PWM_CMPB = PWM_PRD - PWM_phaseshift;
    EPWM_setActionQualifierAction(base2, EPWM_AQ_OUTPUT_A, EPWM_AQ_OUTPUT_LOW,
                                  EPWM_AQ_OUTPUT_ON_TIMEBASE_DOWN_CMPB);
    EPWM_setActionQualifierAction(base2, EPWM_AQ_OUTPUT_A, EPWM_AQ_OUTPUT_HIGH,
                                  EPWM_AQ_OUTPUT_ON_TIMEBASE_UP_CMPA);

  }
  else
  {
      PWM_phaseshift = phaseshift;

    PACK_Sec_PWM_CMPB = PWM_phaseshift + 1U;
    PACK_Sec_PWM_CMPA = PWM_PRD - PWM_phaseshift - 1U;
    EPWM_setActionQualifierAction(base2, EPWM_AQ_OUTPUT_A, EPWM_AQ_OUTPUT_HIGH,
                                  EPWM_AQ_OUTPUT_ON_TIMEBASE_DOWN_CMPB);
    EPWM_setActionQualifierAction(base2, EPWM_AQ_OUTPUT_A, EPWM_AQ_OUTPUT_LOW,
                                  EPWM_AQ_OUTPUT_ON_TIMEBASE_UP_CMPA);
  }

  EPWM_setCounterCompareValue(base2, EPWM_COUNTER_COMPARE_A, PACK_Sec_PWM_CMPA);
  EPWM_setCounterCompareValue(base2, EPWM_COUNTER_COMPARE_B, PACK_Sec_PWM_CMPB);

  EPWM_setTimeBasePeriod(base1, period);

  EPWM_setGlobalLoadOneShotLatch(base1);
  EPWM_forceGlobalLoadOneShotEvent(base1);

  EDIS;
}


#pragma FUNC_ALWAYS_INLINE(PACK_readSensedSignals)
void PACK_runGiGvLoop(void)
{
  float32_t M; // Voltage gain

  PACK_readSensedSignals();

  //
  // Calculations below are based on sensing resistance and calibration
  //
  PACK_VPrimSensed = PACK_VPrimSensed_pu * 3.3f * 0.75f / 0.04903971f;
  PACK_VSecSensed = PACK_VSecSensed_pu * 3.3f / 0.034090909f;
  PACK_iREFPrimSensed = PACK_iREFPrimSensed_pu * 3.3f;
  PACK_iPrimSensed = (PACK_iPrimSensed_pu-PACK_iREFPrimSensed_pu) * 3.3f * 5.0f ;

#if PACKBALANCE_POWER_FLOW == PACKBALANCE_POWER_FLOW_PRIM_SEC
  // Voltage gain
  M = VOLTAGE_RATIO * PACK_VPrimSensed / 48.0f;  
#elif PACKBALANCE_POWER_FLOW == PACKBALANCE_POWER_FLOW_SEC_PRIM
  // Voltage gain
  M = VOLTAGE_RATIO * 24.0f / PACK_VSecSensed;
#endif

// phaseshift should be calculated if not in debug mode
#if PACKBALANCE_WORK_MODE != PACKBALANCE_DEBUG_MODE
    // Phase shift angels calculation based on ZVS realization
    Phaseshift_angle = Km * atanf(M) / (2*PI);

    //
    // Note: Under different load and voltage condition, one may need to adjust parameter Km,
    // in order to decrease the margin of ZVS.                      
    //
#endif

  Phaseshift_angle = (Phaseshift_angle <= 0.0f) ? 0.0f : (Phaseshift_angle >= 0.5f) ? 0.5f : Phaseshift_angle;

  // update phaseshift angles and frequency
  EPWM_setPhaseShiftandTBPRD(PACK_EPWM1_BASE, PACK_EPWM2_BASE, Phaseshift_angle,
                             PRD + PRD_giloop + PRD_gvloop);


#if PACKBALANCE_WORK_MODE == PACKBALANCE_CURRENT_MODE
  //enable current loop
  if (SRCDB_closeGiLoop == 1U)
  {
    //
    // Control loop calculate switching frequency, PRD_giloop and PRD_giloop
    //
    SRCDB_giError = (fabsf(PACK_iREFPrim) - fabsf(PACK_iPrimSensed));

    SRCDB_giOut = SRCDB_GI_IMMEDIATE_RUN(&SRCDB_gi, SRCDB_giError,
                                         SRCDB_giPartialComputedValue);

    SRCDB_giOut =
        (SRCDB_giOut > SRCDB_GI_OUT_MAX) ? SRCDB_GI_OUT_MAX : SRCDB_giOut;
    SRCDB_giOut =
        (SRCDB_giOut < SRCDB_GI_OUT_MIN) ? SRCDB_GI_OUT_MIN : SRCDB_giOut;

    SRCDB_giPartialComputedValue =
        SRCDB_GI_PRECOMPUTE_RUN(&SRCDB_gi, SRCDB_giError, SRCDB_giOut);


    SRCDB_giOut =
        (SRCDB_giOut < SRCDB_GI_OUT_MIN) ? SRCDB_GI_OUT_MIN : SRCDB_giOut;

    PRD_giloop = SRCDB_giOut;
  }
  else
  {
    //
    // If current loop is not closed, reset the controller
    //
    SRCDB_gi.d4 = 0.0f;
    SRCDB_gi.d5 = 0.0f;
    SRCDB_gi.d6 = 0.0f;
    SRCDB_gi.d7 = 0.0f;

    SRCDB_giError = (PACK_iREFPrim - PACK_iPrimSensed);
    SRCDB_gi.d0 = SRCDB_giError;
    SRCDB_gi.d1 = SRCDB_giError;
    SRCDB_gi.d2 = SRCDB_giError;
    SRCDB_gi.d3 = SRCDB_giError;

    SRCDB_giPartialComputedValue = 0.0f;

  }
#endif

#if PACKBALANCE_WORK_MODE == PACKBALANCE_VOLTAGE_MODE

  if (PACK_VPrimSensed >= 26.0f)
  {
      SRCDB_closeGvLoop = 1;
  }

  // enable voltage loop
  if (SRCDB_closeGvLoop == 1U)
  {
    //
    // Control loop calculate switching frequency, PRD_giloop and PRD_giloop
    //
    SRCDB_gvError = (fabsf(PACK_VREFPrim) - fabsf(PACK_VPrimSensed));

    SRCDB_gvOut = SRCDB_GV_IMMEDIATE_RUN(&SRCDB_gv, SRCDB_gvError,
                                         SRCDB_gvPartialComputedValue);

    SRCDB_gvOut = (SRCDB_gvOut > SRCDB_GV_OUT_MAX) ? SRCDB_GV_OUT_MAX : SRCDB_gvOut;
    SRCDB_gvOut = (SRCDB_gvOut < SRCDB_GV_OUT_MIN) ? SRCDB_GV_OUT_MIN : SRCDB_gvOut;

    SRCDB_gvPartialComputedValue =
        SRCDB_GV_PRECOMPUTE_RUN(&SRCDB_gv, SRCDB_gvError, SRCDB_gvOut);

    SRCDB_gvOut = (SRCDB_gvOut < SRCDB_GV_OUT_MIN) ? SRCDB_GV_OUT_MIN : SRCDB_gvOut;

    PRD_gvloop = SRCDB_gvOut;

  }
  else
  {
    //
    // If voltage loop is not closed, reset the controller
    //
    SRCDB_gv.d4 = 0.0f;
    SRCDB_gv.d5 = 0.0f;
    SRCDB_gv.d6 = 0.0f;
    SRCDB_gv.d7 = 0.0f;

    SRCDB_gvError = (fabsf(PACK_VREFPrim) - fabsf(PACK_VPrimSensed));
    SRCDB_gv.d0 = SRCDB_gvError;
    SRCDB_gv.d1 = SRCDB_gvError;
    SRCDB_gv.d2 = SRCDB_gvError;
    SRCDB_gv.d3 = SRCDB_gvError;

    SRCDB_gvPartialComputedValue = 0.0f;

  }
#endif
}

